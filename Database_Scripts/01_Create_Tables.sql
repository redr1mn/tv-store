-- FILE 1: TẠO CƠ SỞ DỮ LIỆU VÀ CÁC BẢNG (CHUẨN THEO SƠ ĐỒ RM)
-- GIAI ĐOẠN 1: CHUẨN HÓA KIỂU DECIMAL(18,2) & BỔ SUNG CHECK CONSTRAINTS
